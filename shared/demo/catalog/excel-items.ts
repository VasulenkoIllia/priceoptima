// Артикул = skuPrefix постачальника + '0000' + номер (123..134). Аналоги в інших постачальників генеруються окремо.
// Ціни (ВХІД/РРЦ) 7 позицій (124, 126-128, 131, 132, 134) скориговано до ринкових: у шаблоні Excel клієнта це умовні
// заглушки (напр. муфта ППР за 2 391,60 грн — ринок 39-47 грн), а не реальні закупівельні ціни. Оригінальні значення
// з шаблону — у templatePurchase/templateRrp. Позиції 123, 125, 129, 130, 133 — правдоподібні, лишені без змін.
