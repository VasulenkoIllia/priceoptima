import type { CanonicalSpec, Style } from './taxonomy-core';
import type { Currency, SupplierKey } from './types';

export interface ExcelItem {
  /** Рядок аркуша «Номенклатура». */
  ref: string;
  /** Номер у артикулі (123..134). */
  num: number;
  supplierKey: SupplierKey;
  nameWork: string;
  name1c: string;
  unit: string;
  currency: Currency;
  /** ВХІД у валюті (для ГРН — у гривнях). */
  purchase: number;
  /** РРЦ у валюті (для ГРН — у гривнях). */
  rrp: number;
  /** Оригінальна ВХІД-ціна з шаблону Excel (заглушка) — лише для 7 скоригованих позицій, довідково. */
  templatePurchase?: number;
  /** Оригінальна РРЦ з шаблону Excel (заглушка) — лише для 7 скоригованих позицій, довідково. */
  templateRrp?: number;
  multiplicity: number;
  /** Постачальники, у яких є аналог (той самий canonicalKey, інший артикул/назва/ціна). */
  analogs: SupplierKey[];
  canonical: CanonicalSpec;
}

const NO_BRAND = 'Без бренду';

function canon(
  key: string, category: string, basePriceUah: number, attrs: Record<string, string | number>,
  names: [string, string][], client: string[], opts: Partial<CanonicalSpec> = {},
): CanonicalSpec {
  return {
    key, category, brand: NO_BRAND, unit: 'шт', multiplicity: 1, minOrderQty: 1, basePriceUah, attrs,
    stock: 'mid', qty: [1, 6], client,
    render: (s: Style) => ({ work: names[s][0], full: names[s][1] }),
    ...opts,
  };
}

